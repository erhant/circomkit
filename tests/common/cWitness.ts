import {execFile} from 'node:child_process';
import {mkdtempSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {promisify} from 'node:util';
import {requireCircom} from '../../src/functions';

/** Whether the C witness calculator can be built here, i.e. whether its tests can run.
 *
 * Its dependencies are not checked by Circomkit itself, so they are checked here to skip the tests if they are missing,
 * except on CI where they must be installed, so that the tests are never skipped without notice.
 */
export const C_WITNESS = await canBuildCWitness();

async function canBuildCWitness(): Promise<boolean> {
  const succeeds = (command: string, args: string[]) =>
    promisify(execFile)(command, args).then(
      () => true,
      () => false
    );

  const missing: string[] = [];
  if (!(await succeeds('make', ['--version']))) missing.push('make');
  if (process.arch === 'x64') {
    // Circom's assembly for the field operations
    if (!(await succeeds('nasm', ['-v']))) missing.push('nasm');
  } else {
    // otherwise `--no_asm` is used, see `compileCircuit`
    await requireCircom('circom', '2.2.2', 'C witness calculator without assembly').catch(err =>
      missing.push(err.message)
    );
  }

  // compiles & links like the Makefile generated by Circom, which needs GMP & nlohmann/json
  const dir = mkdtempSync(join(tmpdir(), 'circomkit-c-witness-'));
  writeFileSync(
    join(dir, 'check.cpp'),
    '#include <gmp.h>\n#include <nlohmann/json.hpp>\nint main() { mpz_t x; mpz_init(x); mpz_clear(x); return nlohmann::json::parse("0").get<int>(); }\n'
  );
  const compiles = await succeeds('g++', [
    '-std=c++11',
    '-O3',
    join(dir, 'check.cpp'),
    '-o',
    join(dir, 'check'),
    '-lgmp',
  ]);
  if (!compiles || !(await succeeds(join(dir, 'check'), []))) {
    missing.push('a C++ compiler (g++) with GMP & nlohmann/json, see the README');
  }
  rmSync(dir, {recursive: true, force: true});

  if (missing.length === 0) return true;
  const message = `The C witness calculator can not be built, missing: ${missing.join('; ')}`;
  if (process.env.CI) throw new Error(message);
  console.warn(`${message}. Its tests are skipped.`);
  return false;
}
